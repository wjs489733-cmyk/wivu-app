// v5 진입 → 홈 → 출석(PIN) → 홈 반전 카드 → 홈 탭 길게 누르기(내 메뉴) 흐름 점검 · 캡처 shots/e-*.png
// 사용: node scripts/flow-entry.mjs [base=http://127.0.0.1:5173/]
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
const base = process.argv[2] ?? 'http://127.0.0.1:5173/';
mkdirSync('shots', { recursive: true });
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const p = await b.newPage({ viewport: { width: 393, height: 852 } });
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
const shot = async (n, wait = 700) => {
  await p.waitForTimeout(wait);
  await p.screenshot({ path: `shots/e-${n}.png` });
};
const hash = () => new URL(p.url()).hash.slice(1);
const steps = [];
const check = (name, ok) => steps.push(`${ok ? 'PASS' : 'FAIL'} ${name}`);

await p.goto(`${base}?frame=0#/splash`);
await shot('01-splash', 500);
await p.waitForTimeout(2200);
check('스플래시 → 온보딩', hash().startsWith('/intro/1'));
await shot('02-onboarding', 200);
await p.getByRole('button', { name: '시작하기' }).click();
await shot('03-login-empty');
check('온보딩 → 로그인', hash().startsWith('/login'));
await p.getByRole('button', { name: /대학교 찾기/ }).click();
await shot('04-school-sheet');
await p.getByRole('button', { name: /대구가톨릭대학교/ }).first().click();
await p.getByLabel('학번').fill('20231234');
await p.getByLabel('비밀번호').fill('12');
await p.getByRole('button', { name: '로그인', exact: true }).click();
await shot('05-login-error', 900);
await p.getByLabel('비밀번호').fill('wivu2026');
await p.getByRole('button', { name: '로그인', exact: true }).click();
await shot('06-loading', 900);
check('로그인 → 정보 불러오는 중', hash().startsWith('/login/linking'));
await p.waitForTimeout(2600);
check('불러오는 중 → 홈', hash().startsWith('/home'));
await shot('07-home', 300);
await p.getByRole('button', { name: '출석 인증하기' }).first().click();
await shot('08-pin');
for (const d of ['4', '8', '2', '7']) await p.getByRole('button', { name: d, exact: true }).click();
await shot('09-pin-filled', 300);
await p.getByRole('button', { name: '인증하기', exact: true }).click();
await shot('10-pin-done', 1500);
const confirm = p.getByRole('button', { name: '확인', exact: true });
if (await confirm.count()) await confirm.first().click();
await shot('11-home-done', 900);
check('출석 완료 후 홈 반전 카드', (await p.getByText('출석 완료').count()) > 0);
const home = p.getByRole('button', { name: '홈', exact: true });
const box = await home.boundingBox();
await p.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
await p.mouse.down();
await p.waitForTimeout(700);
await p.mouse.up();
await shot('12-quick-menu', 600);
check('홈 탭 길게 → 내 메뉴', (await p.getByText(/내 메뉴/).count()) > 0);
console.log(steps.join('\n'));
console.log('url', p.url(), '\nerrors:', errs.length ? errs.join(' | ').slice(0, 1200) : 'none');
await b.close();
